const { JSDOM } = require('../storage/cache/select-tests/node_modules/jsdom');
const { readFileSync } = require('node:fs');
const { resolve } = require('node:path');
const { strict: assert } = require('node:assert');
const dom = new JSDOM(`<form data-enrollment-form><input name="amount" type="number" required value="75000.25"><input name="deposit" type="number" required value="20000.25"><select name="method" required><option>Cash</option><option>Bank transfer</option></select><input name="is_foc" type="checkbox" value="1"></form>`, { runScripts: 'outside-only' });
const { window } = dom;
window.eval(readFileSync(resolve(__dirname, '../public/assets/js/app.js'), 'utf8'));
const form = window.document.querySelector('form');
const amount = form.elements.amount;
const deposit = form.elements.deposit;
const method = form.elements.method;
const foc = form.elements.is_foc;
function toggle(value) { foc.checked = value; foc.dispatchEvent(new window.Event('change')); }
assert.equal(amount.disabled, false);
assert.equal(amount.value, '75000.25');
assert.equal(deposit.step, '0.01');
assert.equal(deposit.max, '75000.25');
deposit.value = '80000';
assert.equal(form.checkValidity(), false);
deposit.value = '20000.25';
toggle(true);
assert.equal(amount.value, '0');
assert.equal(amount.disabled, true);
assert.equal(deposit.disabled, true);
assert.equal(deposit.value, '0');
assert.equal(method.disabled, true);
assert.equal(form.checkValidity(), true);
const data = new window.FormData(form);
assert.equal(data.get('is_foc'), '1');
assert.equal(data.has('amount'), false);
assert.equal(data.has('deposit'), false);
assert.equal(data.has('method'), false);
toggle(false);
assert.equal(amount.value, '75000.25');
assert.equal(amount.disabled, false);
assert.equal(deposit.disabled, false);
assert.equal(deposit.value, '20000.25');
assert.equal(method.disabled, false);
amount.value = '50000';
toggle(true); toggle(false);
assert.equal(amount.value, '50000');
assert.equal(deposit.max, '50000');
deposit.value = '0';
assert.equal(form.checkValidity(), true);
console.log('PASS FOC disables payment fields, submits only the FOC flag, and restores the received amount when unchecked.');
dom.window.close();
