const { JSDOM, VirtualConsole } = require('../storage/cache/select-tests/node_modules/jsdom');
const { readFileSync } = require('node:fs');
const { resolve } = require('node:path');
const { strict: assert } = require('node:assert');
const data = { total: 2, items: [{ name: 'Facebook', count: 2, percentage: 100 }, { name: 'Phone', count: 0, percentage: 0 }] };
const dom = new JSDOM(`<section class="student-origin-panel"><svg class="student-origin-pie"><g class="student-origin-slice" tabindex="0" data-origin-index="0"></g></svg><button data-origin-index="0">Facebook</button><button data-origin-index="1">Phone</button><output data-origin-readout>Hover or focus an origin to see its share.</output></section><script type="application/json" id="student-origin-data">${JSON.stringify(data)}</script>`, { runScripts: 'outside-only' });
const { window } = dom;
window.eval(readFileSync(resolve(__dirname, '../public/assets/js/student-origin.js'), 'utf8'));
const chart = window.document.querySelector('svg');
const output = window.document.querySelector('output');
const facebook = window.document.querySelector('button[data-origin-index="0"]');
facebook.focus();
assert.ok(chart.classList.contains('is-highlighting'));
assert.ok(window.document.querySelector('g').classList.contains('is-active'));
assert.equal(output.textContent, 'Facebook: 2 active students (100%).');
const phone = window.document.querySelector('button[data-origin-index="1"]');
phone.focus();
assert.equal(chart.classList.contains('is-highlighting'), false);
assert.equal(output.textContent, 'Phone: 0 active students (0%).');
phone.blur();
assert.equal(output.textContent, 'Hover or focus an origin to see its share.');
window.document.querySelector('g').dispatchEvent(new window.Event('pointerenter'));
assert.ok(facebook.classList.contains('is-active'));
assert.ok(output.textContent.includes('100%'));
window.document.querySelector('g').dispatchEvent(new window.Event('pointerleave'));
assert.equal(chart.classList.contains('is-highlighting'), false);
dom.window.close();
const errors=[]; const virtualConsole=new VirtualConsole(); virtualConsole.on('jsdomError',error=>errors.push(error));
const styles=new JSDOM(`<style>${readFileSync(resolve(__dirname,'../public/assets/css/student-origin.css'),'utf8')}</style>`,{virtualConsole});
assert.ok(styles.window.document.styleSheets[0]); assert.equal(errors.length,0); styles.window.close();
console.log('PASS Student origin legend and pie synchronize on hover/focus, zero categories remain readable, and chart CSS parses.');
