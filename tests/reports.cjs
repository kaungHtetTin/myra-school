const { JSDOM, VirtualConsole } = require('../storage/cache/select-tests/node_modules/jsdom');
const { readFileSync } = require('node:fs');
const { resolve } = require('node:path');
const { strict: assert } = require('node:assert');
const report = { currency: 'MMK', points: [{ description: '5 January 2024', income: 15000, expense: 20000, profit: -5000 }] };
const dom = new JSDOM(`<form data-report-filters><select name="view"><option value="month">Month</option><option value="year">Year</option></select><label data-report-month><input type="month" name="month" value="2024-01"></label><label data-report-year><input type="number" name="year" value="2024"></label></form><output data-report-readout></output><svg><g tabindex="0" data-report-point="0"></g></svg><script type="application/json" id="finance-report-data">${JSON.stringify(report)}</script>`, { runScripts: 'outside-only' });
const { window } = dom;
window.eval(readFileSync(resolve(__dirname, '../public/assets/js/reports.js'), 'utf8'));
const form = window.document.querySelector('form');
assert.equal(form.elements.month.disabled, false);
assert.equal(form.elements.year.disabled, true);
assert.equal(window.document.querySelector('[data-report-year]').hidden, true);
form.elements.view.value = 'year';
form.elements.view.dispatchEvent(new window.Event('change'));
assert.equal(form.elements.month.disabled, true);
assert.equal(form.elements.year.disabled, false);
assert.equal(new window.FormData(form).has('month'), false);
assert.equal(new window.FormData(form).get('year'), '2024');
assert.equal(form.elements.year.min, '1000');
const point = window.document.querySelector('[data-report-point]');
point.dispatchEvent(new window.Event('focus'));
const text = window.document.querySelector('output').textContent;
assert.ok(text.includes('5 January 2024') && text.includes('150 MMK') && text.includes('200 MMK') && text.includes('-50 MMK'));
form.elements.view.value = 'month';
form.elements.view.dispatchEvent(new window.Event('change'));
assert.equal(new window.FormData(form).get('month'), '2024-01');
assert.equal(new window.FormData(form).has('year'), false);
dom.window.close();
const errors = [];
const virtualConsole = new VirtualConsole();
virtualConsole.on('jsdomError', error => errors.push(error));
const styles = new JSDOM(`<style>${readFileSync(resolve(__dirname, '../public/assets/css/reports.css'), 'utf8')}</style>`, { virtualConsole });
assert.ok(styles.window.document.styleSheets[0]);
assert.equal(errors.length, 0);
styles.window.close();
console.log('PASS Month/year filters submit the correct period, keyboard focus shows exact chart values including losses, and chart CSS parses.');
