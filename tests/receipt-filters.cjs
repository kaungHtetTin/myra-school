const { JSDOM, VirtualConsole } = require('../storage/cache/select-tests/node_modules/jsdom');
const { readFileSync } = require('node:fs');
const { resolve } = require('node:path');
const { strict: assert } = require('node:assert');
const dom = new JSDOM(`<form data-receipt-filters><label>Class<select name="class" data-receipt-class data-searchable><option value="">All classes</option><option value="1" selected>Class One</option><option value="2">Class Two</option></select></label><label>Batch<select name="batch" data-receipt-batch data-searchable><option value="">All batches</option><option value="10" data-class="1" selected>Class One / Morning</option><option value="20" data-class="2" disabled hidden>Class Two / Evening</option></select></label><button>Apply filters</button></form><a download href="/export/fees?class=1&batch=10">Export CSV</a>`, { runScripts: 'outside-only' });
const { window } = dom;
window.HTMLElement.prototype.scrollIntoView = function() {};
for (const file of ['search-select.js','receipts.js']) window.eval(readFileSync(resolve(__dirname, '../public/assets/js',file), 'utf8'));
const course = window.document.querySelector('[name=class]');
const batch = window.document.querySelector('[name=batch]');
const input = batch.closest('.search-select').querySelector('input');
assert.ok(input.value.includes('Morning'));
course.value = '2';
course.dispatchEvent(new window.Event('change', { bubbles: true }));
assert.equal(batch.value, '');
assert.equal(input.value, 'All batches');
assert.equal(batch.options[1].disabled, true);
assert.equal(batch.options[2].disabled, false);
input.focus();
const choices = [...batch.closest('.search-select').querySelectorAll('[role=option]')].map(node=>node.textContent);
assert.deepEqual(choices, ['All batches','Class Two / Evening']);
input.value = 'Evening';
input.dispatchEvent(new window.Event('input', { bubbles: true }));
input.dispatchEvent(new window.KeyboardEvent('keydown', { key: 'Enter', bubbles: true, cancelable: true }));
assert.equal(batch.value, '20');
assert.equal(new window.FormData(window.document.querySelector('form')).get('batch'), '20');
assert.equal(window.document.querySelector('a').getAttribute('href'), '/export/fees?class=1&batch=10');
course.value = '';
course.dispatchEvent(new window.Event('change', { bubbles: true }));
assert.equal(batch.value, '');
assert.equal(batch.options[1].disabled, false);
assert.equal(batch.options[2].disabled, false);
input.click();
assert.equal(batch.closest('.search-select').querySelectorAll('[role=option]').length, 3);
dom.window.close();
const errors=[]; const virtualConsole=new VirtualConsole(); virtualConsole.on('jsdomError',error=>errors.push(error));
const styles=new JSDOM(`<style>${readFileSync(resolve(__dirname,'../public/assets/css/receipts.css'),'utf8')}</style>`,{virtualConsole});
assert.ok(styles.window.document.styleSheets[0]); assert.equal(errors.length,0); styles.window.close();
console.log('PASS Class changes reset the batch, searchable choices update, All classes restores every batch, exports retain applied filters, and filter CSS parses.');
